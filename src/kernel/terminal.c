static size_t g_row;
static size_t g_column;
static size_t g_width;
static size_t g_height;
static size_t g_cursor_row;
static size_t g_cursor_column;
static uint8_t g_color;
static uint16_t *const g_buffer = (uint16_t *)VGA_MEMORY;
static terminal_cell_t g_cells[TERMINAL_MAX_ROWS][TERMINAL_MAX_COLUMNS];
static bool g_use_framebuffer;
static bool g_cursor_visible;
static bool g_framebuffer_locked;
static framebuffer_info_t g_framebuffer;

static uint16_t vga_entry(unsigned char c, uint8_t color) {
    return (uint16_t)c | (uint16_t)color << 8;
}

static uint32_t terminal_color_to_rgb(uint8_t color) {
    static const uint32_t g_palette[16] = {
        0x00000000u, 0x000000AAu, 0x0000AA00u, 0x0000AAAAu,
        0x00AA0000u, 0x00AA00AAu, 0x00AA5500u, 0x00AAAAAAu,
        0x00555555u, 0x005555FFu, 0x0055FF55u, 0x0055FFFFu,
        0x00FF5555u, 0x00FF55FFu, 0x00FFFF55u, 0x00FFFFFFu
    };

    return g_palette[color & 0x0Fu];
}

static void framebuffer_plot(uint32_t x, uint32_t y, uint32_t color) {
    uint8_t *const base = (uint8_t *)g_framebuffer.address;
    uint8_t *const pixel = base + y * g_framebuffer.pitch + x * (g_framebuffer.bpp / 8u);

    pixel[0] = (uint8_t)(color & 0xFFu);
    pixel[1] = (uint8_t)((color >> 8) & 0xFFu);
    pixel[2] = (uint8_t)((color >> 16) & 0xFFu);

    if (g_framebuffer.bpp == 32u) {
        pixel[3] = 0;
    }
}

static void terminal_draw_framebuffer_cell(size_t x, size_t y, bool cursor) {
    if (!g_use_framebuffer || g_framebuffer_locked || x >= g_width || y >= g_height) {
        return;
    }

    const terminal_cell_t cell = g_cells[y][x];
    const uint8_t fg = cell.color & 0x0Fu;
    const uint8_t bg = (uint8_t)((cell.color >> 4) & 0x0Fu);
    const uint32_t fg_color = terminal_color_to_rgb(fg);
    const uint32_t bg_color = terminal_color_to_rgb(bg);
    const unsigned char ch = (unsigned char)cell.ch;
    const uint8_t *glyph = (ch >= 32u && ch <= 127u) ? g_font[ch - 32u] : g_font[0];
    const uint32_t origin_x = (uint32_t)x * FONT_WIDTH;
    const uint32_t origin_y = (uint32_t)y * FONT_HEIGHT;

    for (uint32_t py = 0; py < FONT_HEIGHT; ++py) {
        const uint8_t row_bits = glyph[py / 2u];
        for (uint32_t px = 0; px < FONT_WIDTH; ++px) {
            const bool bit_set = (row_bits & (uint8_t)(0x80u >> px)) != 0u;
            framebuffer_plot(origin_x + px, origin_y + py, bit_set ? fg_color : bg_color);
        }
    }

    if (cursor) {
        const uint32_t cursor_y = origin_y + FONT_HEIGHT - 2u;
        for (uint32_t px = 0; px < FONT_WIDTH; ++px) {
            framebuffer_plot(origin_x + px, cursor_y, fg_color);
        }
    }
}

static void terminal_update_cursor(void) {
    if (g_use_framebuffer) {
        if (g_framebuffer_locked) {
            g_cursor_column = g_column;
            g_cursor_row = g_row;
            g_cursor_visible = false;
            return;
        }

        if (g_cursor_visible && g_cursor_column < g_width && g_cursor_row < g_height) {
            terminal_draw_framebuffer_cell(g_cursor_column, g_cursor_row, false);
        }

        g_cursor_column = g_column;
        g_cursor_row = g_row;
        g_cursor_visible = true;
        terminal_draw_framebuffer_cell(g_cursor_column, g_cursor_row, true);
        return;
    }

    uint16_t position = (uint16_t)(g_row *   VGA_WIDTH + g_column);

    outb(0x3D4, 0x0F);
    outb(0x3D5, (uint8_t)(position & 0xFF));

    outb(0x3D4, 0x0E);
    outb(0x3D5, (uint8_t)((position >> 8) & 0xFF));
}

static void terminal_write_cell(size_t x, size_t y) {
    if (x >= g_width || y >= g_height) {
        return;
    }

    if (g_use_framebuffer) {
        if (g_framebuffer_locked) {
            return;
        }
        terminal_draw_framebuffer_cell(x, y, x == g_column && y == g_row);
        return;
    }

    g_buffer[y * VGA_WIDTH + x] = vga_entry((unsigned char)g_cells[y][x].ch, g_cells[y][x].color);
}

static void scroll_if_needed(void) {
    if (g_row < g_height) {
        return;
    }

    for (size_t y = 1; y < g_height; ++y) {
        for (size_t x = 0; x < g_width; ++x) {
            g_cells[y - 1][x] = g_cells[y][x];
        }
    }

    for (size_t x = 0; x < g_width; ++x) {
        g_cells[g_height - 1][x].ch = ' ';
        g_cells[g_height - 1][x].color = g_color;
    }

    if (g_use_framebuffer) {
        if (!g_framebuffer_locked) {
            for (size_t y = 0; y < g_height; ++y) {
                for (size_t x = 0; x < g_width; ++x) {
                    terminal_draw_framebuffer_cell(x, y, false);
                }
            }
        }
    } else {
        for (size_t y = 0; y < g_height; ++y) {
            for (size_t x = 0; x < g_width; ++x) {
                terminal_write_cell(x, y);
            }
        }
    }

    g_row = g_height - 1;
}

void terminal_configure_framebuffer(const framebuffer_info_t *framebuffer) {
    g_use_framebuffer = false;
    g_framebuffer.address = 0;
    g_framebuffer.pitch = 0;
    g_framebuffer.width = 0;
    g_framebuffer.height = 0;
    g_framebuffer.bpp = 0;
    g_framebuffer.type = 0;
    g_framebuffer.available = false;

    if (framebuffer == 0) {
        return;
    }

    if (!framebuffer->available || framebuffer->address == 0) {
        return;
    }

    if (framebuffer->type != 1u || (framebuffer->bpp != 24u && framebuffer->bpp != 32u)) {
        return;
    }

    if (framebuffer->width < FONT_WIDTH || framebuffer->height < FONT_HEIGHT) {
        return;
    }

    g_framebuffer = *framebuffer;
    g_use_framebuffer = true;
}

void terminal_initialize(void) {
    g_width = g_use_framebuffer ? (size_t)(g_framebuffer.width / FONT_WIDTH) : VGA_WIDTH;
    g_height = g_use_framebuffer ? (size_t)(g_framebuffer.height / FONT_HEIGHT) : VGA_HEIGHT;

    if (g_width > TERMINAL_MAX_COLUMNS) {
        g_width = TERMINAL_MAX_COLUMNS;
    }

    if (g_height > TERMINAL_MAX_ROWS) {
        g_height = TERMINAL_MAX_ROWS;
    }

    g_row = 0;
    g_column = 0;
    g_cursor_row = 0;
    g_cursor_column = 0;
    g_color = 0x0F;
    g_cursor_visible = false;
    terminal_clear();
}

void terminal_clear(void) {
    if (g_use_framebuffer && !g_framebuffer_locked) {
        for (uint32_t y = 0; y < g_framebuffer.height; ++y) {
            for (uint32_t x = 0; x < g_framebuffer.width; ++x) {
                framebuffer_plot(x, y, terminal_color_to_rgb((uint8_t)((g_color >> 4) & 0x0Fu)));
            }
        }
    }

    for (size_t y = 0; y < g_height; ++y) {
        for (size_t x = 0; x < g_width; ++x) {
            g_cells[y][x].ch = ' ';
            g_cells[y][x].color = g_color;
            if (!g_use_framebuffer) {
                g_buffer[y * VGA_WIDTH + x] = vga_entry(' ', g_color);
            }
        }
    }

    g_row = 0;
    g_column = 0;
    terminal_update_cursor();
}

void terminal_put_char(char c) {
    if (c == '\n') {
        g_column = 0;
        ++g_row;
        scroll_if_needed();
        terminal_update_cursor();
        return;
    }

    if (c == '\r') {
        g_column = 0;
        terminal_update_cursor();
        return;
    }

    if (c == '\b') {
        if (g_column > 0) {
            --g_column;
        } else if (g_row > 0) {
            --g_row;
            g_column = VGA_WIDTH - 1;
        } else {
            terminal_update_cursor();
            return;
        }

        g_cells[g_row][g_column].ch = ' ';
        g_cells[g_row][g_column].color = g_color;
        terminal_write_cell(g_column, g_row);
        terminal_update_cursor();
        return;
    }

    g_cells[g_row][g_column].ch = c;
    g_cells[g_row][g_column].color = g_color;
    terminal_write_cell(g_column, g_row);

    ++g_column;
    if (g_column == g_width) {
        g_column = 0;
        ++g_row;
        scroll_if_needed();
    }
    terminal_update_cursor();
}

void terminal_write(const char *data) {
    while (*data != '\0') {
        terminal_put_char(*data++);
    }
}

void terminal_write_line(const char *data) {
    terminal_write(data);
    terminal_put_char('\n');
}

void terminal_set_color(uint8_t color) {
    g_color = color;
}

uint8_t terminal_get_color(void) {
    return g_color;
}

static void terminal_redraw_framebuffer(void) {
    if (!g_use_framebuffer || g_framebuffer_locked) {
        return;
    }

    for (size_t y = 0; y < g_height; ++y) {
        for (size_t x = 0; x < g_width; ++x) {
            terminal_draw_framebuffer_cell(x, y, false);
        }
    }

    g_cursor_visible = false;
    terminal_update_cursor();
}

void terminal_set_framebuffer_lock(bool locked) {
    const bool was_locked = g_framebuffer_locked;
    g_framebuffer_locked = locked;

    if (!was_locked && locked) {
        g_cursor_visible = false;
        return;
    }

    if (was_locked && !locked) {
        terminal_redraw_framebuffer();
    }
}
